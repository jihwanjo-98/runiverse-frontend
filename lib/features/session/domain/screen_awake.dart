/// 화면이 저절로 꺼지지 않게 붙잡아 두는 것.
///
/// 이번 구현은 **포그라운드 전용**이라 화면이 꺼지면 추적도 멈춘다.
/// 달리는 동안에는 화면을 켜 둬야 한다.
///
/// ⚠️ **끝나면 반드시 푼다.** 안 풀면 앱을 나가도 화면이 안 꺼져서 배터리가 마른다.
///
/// 인터페이스로 두는 이유는 위젯 테스트다. 플랫폼 채널을 직접 부르면
/// 테스트에서 채널이 없어 죽는다.
abstract interface class ScreenAwake {
  Future<void> enable();
  Future<void> disable();
}
